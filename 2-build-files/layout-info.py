#!/usr/bin/env python3
#
# ******************************************************************************
#
# BBC MICRO DISC ELITE (MODEL B PORT) LAYOUT INFORMATION SCRIPT
#
# Run by the Makefile from the repository's root, after the loader has been
# assembled and before the programs are. From the loader's symbols
# (3-assembled-output/loader-symbols.txt, which "beebasm -d" writes) it
# produces 3-assembled-output/resident.asm: the addresses in the loader's
# resident block A (elite-resident.asm, main RAM &0400-&07FF) that the
# programs call or read, which the layout files (elite-layout-flight.asm,
# elite-layout-docked.asm) INCLUDE:
#
#   * the far calls between a program's home and cold banks (farC, farCj,
#     farH, farHj) and the bank numbers the loader found (BANKH, BANKC,
#     BANKR, BANKF);
#
#   * PCLI, the game's OSCLI (OSCLI = PCLI in the programs' sources)
#
#   * IRQG, the game's interrupt handler, and NA% (the last saved
#     commander), CHK2, CHK and BRBR1 (the break handler), which were the
#     original's block B at &1100
#
# It also writes 3-assembled-output/flight-banks.txt and docked-banks.txt,
# the bank of each label of each program, for the harness (below).
#
# (docs/memory-map.md)
#
# ******************************************************************************

import re

OUT = "3-assembled-output/"
NAMES = ("farC", "farCj", "farH", "farHj", "BANKH", "BANKC", "BANKR", "BANKF", "PCLI",
         "IRQG", "NA%", "CHK2", "CHK", "BRBR1", "PANR", "RSHOW")

sy = {}
for m in re.finditer(r"'([^']+)':(\d+)", open(OUT + "loader-symbols.txt").read()):
    sy.setdefault(m.group(1), int(m.group(2)))

with open(OUT + "resident.asm", "w") as f:
    f.write("\\ Generated by 2-build-files/layout-info.py from the loader's symbols:\n")
    f.write("\\ the loader's resident block A (elite-resident.asm)\n\n")
    for n in NAMES:
        f.write(" %s = &%04X\n" % (n, sy[n]))


# The banks of the programs' labels, for the harness (6-harness/blib.mjs):
# 3-assembled-output/<program>-banks.txt, "label C" for each label assembled
# in the program's cold bank (its cold copy and the text tokens), "label H"
# for each label of its home bank's copies (whose addresses are at
# &8000-&BFFF once assembled; the workspaces' labels in those copies are in
# main RAM, which the harness tells by address)


def labels(path):
    return re.findall(r"^\s*\.([A-Za-z_][\w%]*)", open(path, encoding="latin-1").read(), re.M)


for prog in ("flight", "docked"):
    with open(OUT + "%s-banks.txt" % prog, "w") as f:
        for name in labels(OUT + "elite-%s-cold.asm" % prog) + labels(OUT + "elite-tokens-cold.asm"):
            f.write("%s C\n" % name)
        for name in labels(OUT + "elite-%s-home.asm" % prog) + labels(OUT + "elite-%s-blueprints.asm" % prog):
            f.write("%s H\n" % name)
