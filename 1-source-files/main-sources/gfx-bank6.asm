\ ******************************************************************************
\
\ gfx-bank6.asm - bank 6: the filled renderer's frame layer (docs/renderer.md)
\
\ Port (Model B): the BBC Master port's bank 6 (its elite-gfx.asm's), laid out
\ for the Model B, assembled by 2-build-files/bank6.py once the flight program
\ is (it reads the game's addresses from the flight program's symbols, and
\ the banks' from the loader's, into 3-assembled-output/bank6-game.asm):
\
\   &8000        the frame layer (gfx-frame.asm), the lens flare (gfx-flare.asm,
\                gfx-flare6.asm), the hangar (gfx-hangar.asm), the bookkeeping
\                for the screens drawn directly (gfx-frame_cold.asm), F_INIT
\                (gfx-finit.asm), then the ships' faces and the lighting's
\                ramps (gfx-faces.asm, gfx-light6.asm, generated by
\                2-build-files/faces.py; the lighting itself, gfx-light.asm,
\                and the faces' normals, gfx-normals.asm, are in the game's
\                bank 4, with the quarter squares)
\   then         the state: the ship records (F_RP, F_SR), the text map (F_TM,
\                F_TMR), the discs' half-widths (F_HW, F_HW2, page aligned),
\                the zero page F_FRAME keeps (f_zsv), the docking slot (F_SLV)
\   FJT (&BFC0)  the dispatcher: GCALL (gfx-glue.asm) enters here with X =
\                an entry's number (FG_*), A in GA
\
\ It also assembles the main RAM glue (gfx-glue.asm) at GLUE%, as the
\ resident block includes it, and writes it to GLUE.bin for the test
\ (6-harness/test_frame.py).
\
\ ******************************************************************************

 INCLUDE "1-source-files/main-sources/elite-map.asm"
 INCLUDE "3-assembled-output/bank6-game.asm"
 INCLUDE "1-source-files/main-sources/gfx-rws.asm"

 CPU 0

 CLEAR GLUE%, DTMP
 ORG GLUE%
 GUARD DTMP
 INCLUDE "1-source-files/main-sources/gfx-glue.asm"
 SAVE "3-assembled-output/GLUE.bin", GLUE%, GLUE_END, GLUE%

 CLEAR &8000, &C000
 ORG &8000

 INCLUDE "1-source-files/main-sources/gfx-frame.asm"
 INCLUDE "1-source-files/main-sources/gfx-flare.asm"
 INCLUDE "1-source-files/main-sources/gfx-flare6.asm"
 INCLUDE "1-source-files/main-sources/gfx-frame_cold.asm"
 INCLUDE "1-source-files/main-sources/gfx-hangar.asm"
 INCLUDE "1-source-files/main-sources/gfx-finit.asm"
.F_CODEEND
 INCLUDE "1-source-files/main-sources/gfx-faces.asm"
 INCLUDE "1-source-files/main-sources/gfx-light6.asm"
.F_TABEND
.F_RP   SKIP 29 * MAXSH \ the ship records (F_SHIP): INWK 0-8, XX16, XX0, each
F_SZL = F_RP + 6 * MAXSH  \ a field to an array of MAXSH (the ship's z, INWK
F_SZH = F_RP + 7 * MAXSH  \ 6-7: the sort's)
IF HI(P%) <> HI(P% + 23) \ (F_TMR whole in a page: f_text2 reads it every
 SKIP &100 - LO(P%)     \ frame, by row)
ENDIF
.F_TMR  SKIP 24         \ the text map's non-empty cells per row
.f_tcol SKIP 1          \ (f_char1's column)
.f_zsv  SKIP &22 + 16   \ F_FRAME's keep of &06-&27 and FZ's &D2-&E1
F_SRN = MAXSH * 15      \ (the most faces is 15)
.F_SR   SKIP F_SRN      \ the ships' faces' levels (F_SHIP)
.F_SLV  SKIP 52         \ the docking slot's vertices, as R_PXL .. R_PYH + 3
                        \ (f_poly2, f_slot: gfx-frame_cold.asm; x high of
                        \ vertex 0, F_SLV+16, &80: none)
 ALIGN &100
.F_HW   SKIP 256        \ the planet's half-widths (f_hwbuild)
.F_HW2  SKIP 256        \ the sun's
.F_TM   SKIP 768        \ the text map: desired characters, 24 rows of 32
.F_END
 ASSERT F_END <= FCSLOT \ the face lists of the blueprint set loaded, to FJT
                        \ (FCSLOT and its size: gfx-faces.asm; F_SETLD)

 ORG FJT                \ the dispatcher: X = the entry (FG_*), A = GA
 LDA fjt_hi,X
 PHA
 LDA fjt_lo,X
 PHA
 LDA GA
 RTS                    \ (to the entry, which returns to GCALL)
.fjt_lo
 EQUB LO(F_INIT-1), LO(F_DIRECT-1), LO(F_FRAME-1), LO(F_SHIP-1)
 EQUB LO(F_LINE-1), LO(F_PDOT-1), LO(F_PLANET-1), LO(F_SHPPT-1)
 EQUB LO(F_PCURVE-1), LO(F_PPOINT-1), LO(F_CHAR-1), LO(F_DELCHAR-1)
 EQUB LO(F_CLRTEXT-1), LO(F_GUN-1), LO(F_HANG0-1), LO(F_HANGAR-1)
 EQUB LO(F_CLOUD-1), LO(F_SETLD-1)
.fjt_hi
 EQUB HI(F_INIT-1), HI(F_DIRECT-1), HI(F_FRAME-1), HI(F_SHIP-1)
 EQUB HI(F_LINE-1), HI(F_PDOT-1), HI(F_PLANET-1), HI(F_SHPPT-1)
 EQUB HI(F_PCURVE-1), HI(F_PPOINT-1), HI(F_CHAR-1), HI(F_DELCHAR-1)
 EQUB HI(F_CLRTEXT-1), HI(F_GUN-1), HI(F_HANG0-1), HI(F_HANGAR-1)
 EQUB HI(F_CLOUD-1), HI(F_SETLD-1)
.FJT_END
 ASSERT fjt_hi - fjt_lo = FG_N AND FJT_END <= &C000

PRINT "Bank 6 (frame layer): code &8000-", ~F_CODEEND-1, " (", F_CODEEND-&8000, " bytes), tables ", ~F_CODEEND, "-", ~F_TABEND-1, " (", F_TABEND-F_CODEEND, "), state ", ~F_TABEND, "-", ~F_END-1, ", free ", FCSLOT-F_END, ", the face lists' slot ", ~FCSLOT, "-", ~FJT-1, ", the dispatcher ", ~FJT, "-", ~FJT_END-1
PRINT "Glue (main RAM): ", ~GLUE%, "-", ~GLUE_END-1, " (", GLUE_END-GLUE%, " bytes: trampolines ", rtramp_end-GLUE%, ", GCALL ", GLUE_END-GCALL, ")"

 SAVE "3-assembled-output/BANK6.bin", &8000, &C000, &8000
