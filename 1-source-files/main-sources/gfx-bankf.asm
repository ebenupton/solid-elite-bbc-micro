\ ******************************************************************************
\
\ gfx-bankf.asm - bank F: the filled renderer's frame layer (docs/renderer.md)
\
\ Port (Model B): assembled by 2-build-files/bankf.py once the flight program
\ is (it reads the game's addresses from the flight program's symbols, and
\ the banks' from the loader's, into 3-assembled-output/bankf-game.asm):
\
\   &8000        the frame layer (gfx-frame.asm), the lighting (gfx-light.asm),
\                the faces and lighting tables (gfx-faces.asm, gfx-light6.asm,
\                both generated by 2-build-files/faces.py)
\   page-aligned the lighting's quarter squares (F_QSL, F_QSH), the discs'
\                half-widths (F_HW for the planet, F_HW2 for the sun), the
\                text map (F_TM, 24 rows of 32 cells) and the ships' records
\                (F_DL)
\   FJT (&BFC0)  the dispatcher: GCALL (gfx-glue.asm) enters here with X =
\                an entry's number (FG_*), A in GA
\
\ It also assembles the main RAM glue (gfx-glue.asm) at GLUE%, as the
\ resident block is to include it, and writes it to GLUE.bin, for the test
\ (6-harness/test_frame.py); nothing loads either yet.
\
\ ******************************************************************************

 INCLUDE "1-source-files/main-sources/elite-map.asm"
 INCLUDE "3-assembled-output/bankf-game.asm"
 INCLUDE "1-source-files/main-sources/gfx-rws.asm"

 CPU 0

 CLEAR GLUE%, DTMP
 ORG GLUE%
 GUARD DTMP
 INCLUDE "1-source-files/main-sources/gfx-glue.asm"
 SAVE "3-assembled-output/GLUE.bin", GLUE%, GLUE_END, GLUE%

 CLEAR &8000, &C000
 ORG &8000

 INCLUDE "1-source-files/main-sources/gfx-frame.asm"
 INCLUDE "1-source-files/main-sources/gfx-light.asm"
 INCLUDE "1-source-files/main-sources/gfx-flare.asm"
 INCLUDE "1-source-files/main-sources/gfx-hangar.asm"
.F_CODEEND
 INCLUDE "1-source-files/main-sources/gfx-faces.asm"
 INCLUDE "1-source-files/main-sources/gfx-light6.asm"
.F_TABEND

 ALIGN &100
.F_QSL                  \ the quarter squares QS(n) = INT(n * n / 4), n = 0
 FOR n, 0, 255          \ to 255 (the lighting's: gfx-light.asm)
  EQUB LO(n * n DIV 4)
 NEXT
.F_QSH
 FOR n, 0, 255
  EQUB HI(n * n DIV 4)
 NEXT
.F_HW    SKIP 256       \ the planet's half-widths (f_hwbuild)
.F_HW2   SKIP 256       \ the sun's
.F_TM    SKIP 768       \ the text map: a cell is a character (32..127) or 0
.F_DL    SKIP &800      \ the ships' records (F_SHIP)
.F_DLEND
 ASSERT LO(F_DLEND) = 0 AND F_DLEND <= FJT

 ORG FJT                \ the dispatcher: X = the entry (FG_*), A = GA
 LDA fjt_hi,X
 PHA
 LDA fjt_lo,X
 PHA
 LDA GA
 RTS                    \ (to the entry, which returns to GCALL)
.fjt_lo
 EQUB LO(F_INIT-1), LO(F_DIRECT-1), LO(F_FRAME-1), LO(F_SHIP-1)
 EQUB LO(F_LINE-1), LO(F_DOT-1), LO(F_PLANET-1), LO(F_SHPPT-1)
 EQUB LO(F_PCURVE-1), LO(F_PPOINT-1), LO(F_CHAR-1), LO(F_DELCHAR-1)
 EQUB LO(F_CLRTEXT-1), LO(F_BOMB-1), LO(F_HANG0-1), LO(F_HANGAR-1)
.fjt_hi
 EQUB HI(F_INIT-1), HI(F_DIRECT-1), HI(F_FRAME-1), HI(F_SHIP-1)
 EQUB HI(F_LINE-1), HI(F_DOT-1), HI(F_PLANET-1), HI(F_SHPPT-1)
 EQUB HI(F_PCURVE-1), HI(F_PPOINT-1), HI(F_CHAR-1), HI(F_DELCHAR-1)
 EQUB HI(F_CLRTEXT-1), HI(F_BOMB-1), HI(F_HANG0-1), HI(F_HANGAR-1)
.FJT_END
 ASSERT fjt_hi - fjt_lo = FG_N AND FJT_END <= &C000

PRINT "Bank F (frame layer): code &8000-", ~F_CODEEND-1, " (", F_CODEEND-&8000, " bytes), tables ", ~F_CODEEND, "-", ~F_TABEND-1, " (", F_TABEND-F_CODEEND, "), state ", ~F_QSL, "-", ~F_DLEND-1, ", free ", FJT-F_DLEND, " (+", F_QSL-F_TABEND, " alignment), the dispatcher ", ~FJT, "-", ~FJT_END-1
PRINT "Glue (main RAM): ", ~GLUE%, "-", ~GLUE_END-1, " (", GLUE_END-GLUE%, " bytes: trampolines ", rtramp_end-GLUE%, ", GCALL ", GLUE_END-GCALL, ")"

 SAVE "3-assembled-output/F.bin", &8000, &C000, &8000
