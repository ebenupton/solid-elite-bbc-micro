#!/usr/bin/env node
// gen-ev.mjs ELITE_AGENT_CPLAYER_DIR OUT.h: elite-agent's address table for the
// Stairway to Hell release of disc Elite, the gate's reference
// (4-reference-binaries/sth), as a C initialiser for agentd.c.
//
// elite-agent (cplayer/elite_ver.c) knows the disc version as Mark Moxon's
// flicker-free build, whose commander block from QQ8 on and a few variables
// sit two bytes lower than the release's (QQ8, QQ9, QQ10, COMC, DAMP, DJD,
// PATG, JSTGY, JSTE, JSTK, tek), and whose QQ29 is in zero page; and it
// recognises that build's code bytes, not the release's. So agentd does not
// let it look: it sets g_ev from this table, whose every address is the
// release's symbol of the same name (flight and docked programs agreeing, or
// the loader's for NA%), and whose other fields (NI%, the save check's
// length, the title screens' ships, the fire key, kills by type) are the disc
// table's as elite-agent has them. A field that is 0 in elite-agent's disc
// table (not in the disc version: TALLYL, distaway) stays 0.
import { readFileSync, writeFileSync } from "fs";
import { loadSyms } from "../blib.mjs";
const [cp, out] = process.argv.slice(2);
const STH = decodeURIComponent(new URL("../../4-reference-binaries/sth/", import.meta.url).pathname);
const F = loadSyms(`${STH}flight-symbols.txt`), D = loadSyms(`${STH}docked-symbols.txt`), L = loadSyms(`${STH}loader-symbols.txt`);
const h = readFileSync(`${cp}/elite_ver.h`, "utf8"), c = readFileSync(`${cp}/elite_ver.c`, "utf8");
const fields = [...h.slice(h.indexOf("uint16_t A_"), h.indexOf(";", h.indexOf("uint16_t A_"))).matchAll(/A_\w+/g)].map(m => m[0]);
const disc = c.slice(c.indexOf("static const elite_ver_t DISC"), c.indexOf("};", c.indexOf("static const elite_ver_t DISC")));
const discVal = Object.fromEntries([...disc.matchAll(/\.(A_\w+) = (0x[0-9A-Fa-f]+|0)\b/g)].map(m => [m[1], parseInt(m[2])]));
const tail = /\.ni = [^\n]*/.exec(disc)[0].replace(/,\s*$/, "");
const sym = { A_K_PC: "K%", A_NA_PC: "NA%" };
const lines = [], moved = [];
for (const f of fields) {
    if (discVal[f] === undefined) throw new Error(`${f}: not in elite-agent's disc table`);
    let v = 0;
    if (discVal[f] !== 0) {
        const n = sym[f] || f.slice(2);
        const fv = F[n], dv = D[n];
        if (fv !== undefined && dv !== undefined && fv !== dv) throw new Error(`${n}: flight &${fv.toString(16)}, docked &${dv.toString(16)}`);
        v = fv ?? dv ?? L[n];
        if (v === undefined) throw new Error(`${n}: no symbol in the release`);
        if (v !== discVal[f]) moved.push(`${n} &${discVal[f].toString(16)}->&${v.toString(16)}`);
    }
    lines.push(`.${f} = 0x${v.toString(16).toUpperCase().padStart(4, "0")}`);
}
writeFileSync(out, `// generated by 6-harness/agentplay/gen-ev.mjs from 4-reference-binaries/sth's symbols: do not edit
// (moved from elite-agent's disc table: ${moved.join(", ") || "none"})
#define EV_STH_INIT { .id = EV_BBC_DISC, .name = "BBC Micro disc Elite (Stairway to Hell release)", \\
    ${lines.join(", ")}, \\
    ${tail} }
`);
console.log(`${out}: ${fields.length} addresses, ${moved.length} moved from elite-agent's disc table (${moved.join(", ")})`);
